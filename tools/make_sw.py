#!/usr/bin/env python3
"""Generates app/sw.js with a precache list and a version hash of every shipped file."""
import os, hashlib, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, 'app')
files = []
for d, _, fs in os.walk(APP):
    for f in fs:
        p = os.path.relpath(os.path.join(d, f), APP).replace(os.sep, '/')
        if p == 'sw.js' or p.startswith('vendor/pdfjs/') or p.endswith('.map'):
            continue
        files.append(p)
files.sort()
h = hashlib.sha256()
for p in files:
    h.update(p.encode()); h.update(open(os.path.join(APP, p), 'rb').read())
ver = h.hexdigest()[:12]
tpl = r'''// Generated by tools/make_sw.py. Do not edit.
const VERSION = "%(ver)s";
const CACHE = "cfp-" + VERSION;
const PRECACHE = %(files)s;

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((p) => new Request(p, { cache: "reload" })))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("cfp-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || !req.url.startsWith(self.location.origin)) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((res) => {
    if (res && res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => req.mode === "navigate" ? caches.match("index.html") : Response.error())));
});
'''
open(os.path.join(APP, 'sw.js'), 'w').write(tpl % {'ver': ver, 'files': json.dumps(files, indent=1)})
print('sw.js', ver, len(files), 'files')
